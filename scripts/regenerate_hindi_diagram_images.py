import os
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

FONT_PATH = r"C:\Windows\Fonts\NIRMALAB.TTF"
FONT_REGULAR = r"C:\Windows\Fonts\NIRMALA.TTF"

def create_hindi_diagram(title: str, subtitle: str, concept1: str, concept2: str, concept3: str, out_path: Path):
    width, height = 1280, 720
    img = Image.new('RGB', (width, height), color=(15, 23, 42)) # bg-slate-900
    draw = ImageDraw.Draw(img)

    try:
        f_title = ImageFont.truetype(FONT_PATH, 38)
        f_sub = ImageFont.truetype(FONT_REGULAR, 22)
        f_card_title = ImageFont.truetype(FONT_PATH, 20)
        f_card_text = ImageFont.truetype(FONT_REGULAR, 18)
    except Exception as e:
        print(f"Error loading Nirmala font: {e}")
        return

    # Draw Title Header
    draw.text((640, 70), title, font=f_title, fill=(251, 191, 36), anchor="mm") # amber-400
    draw.text((640, 130), subtitle, font=f_sub, fill=(203, 213, 225), anchor="mm") # slate-300

    # Draw 3 Concept Cards
    cards = [
        ("मुख्य भाव (Core Concept)", concept1, (20, 184, 166)), # teal
        ("भाषा व शब्द भंडार (Vocabulary)", concept2, (99, 102, 241)), # indigo
        ("जीवन मूल्य व सीख (Values)", concept3, (245, 158, 11)) # amber
    ]

    card_w, card_h = 360, 420
    card_y = 220
    spacing = 40
    start_x = (width - (3 * card_w + 2 * spacing)) // 2

    for idx, (c_hdr, c_text, border_rgb) in enumerate(cards):
        cx = start_x + idx * (card_w + spacing)

        # Card background & border
        draw.rectangle([cx, card_y, cx + card_w, card_y + card_h], fill=(30, 41, 59), outline=border_rgb, width=3) # bg-slate-800

        # Card Header
        draw.rectangle([cx, card_y, cx + card_w, card_y + 55], fill=border_rgb)
        draw.text((cx + card_w // 2, card_y + 28), c_hdr, font=f_card_title, fill=(255, 255, 255), anchor="mm")

        # Card Text Wrapping
        words = c_text.split()
        lines = []
        curr_line = []
        for w in words:
            curr_line.append(w)
            bbox = draw.textbbox((0, 0), " ".join(curr_line), font=f_card_text)
            if bbox[2] - bbox[0] > card_w - 40:
                curr_line.pop()
                lines.append(" ".join(curr_line))
                curr_line = [w]
        if curr_line:
            lines.append(" ".join(curr_line))

        ty = card_y + 80
        for line in lines[:10]:
            draw.text((cx + 20, ty), line, font=f_card_text, fill=(226, 232, 240)) # slate-200
            ty += 32

    out_path.parent.mkdir(parents=True, exist_ok=True)
    img.save(out_path, quality=95)
    print(f"Successfully rendered crisp Devanagari diagram to {out_path.name}")

